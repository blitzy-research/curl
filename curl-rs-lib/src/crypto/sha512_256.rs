    /// The capability predicate answers, and answers unconditionally.
    ///
    /// `crate::version` pins this signature with a `const _: fn() -> bool`
    /// beside its engine registry, so the only thing left to check is the
    /// value. It is `true` at every feature setting because no feature gates
    /// this module: `lib/curl_sha512_256.h:28`'s two C switches have no Cargo
    /// counterpart, and a `cfg` naming one would compile the digest away in
    /// silence.
    #[test]
    fn the_capability_predicate_reports_the_digest_as_present() {
        assert!(available());

        // And the thing it claims to be present really answers, which is what
        // keeps the claim substantive rather than a bare boolean.
        assert_eq!(sha512_256(TEST_STR3), PRECOMP_HASH3);
    }
